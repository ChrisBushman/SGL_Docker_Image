; graphic character print routine for 32k color mode
; input
;	R1 = ascii character to print
;	R2 = X pos on screen
;	R3 = Y pos on screen
;	R4 = foreground text color
;	R5 = Background text color

Gputc

	mov	#32,r6
	sub	r6,r1
	mov	#32,r6
	mulu	r6,r1
	sts	macl,r1
	mov.l	#font,r9
	add	r1,r9		; R0 = address of character bitmap

	mov.l	#1024,r6
	mulu	r6,r3
	sts	macl,r3
	shll	r2
	add	r3,r2		; R2 = address of screen location
	mov.l	#VDP1_FBUF,r3
	add	r3,r2

	mov.l	#1008,r3

	mov	#8,r6
	mov.l	#$F0000000,r10
@rowloop:
	mov	#8,r7
	mov.l	@r9+,r0
@colloop:
	tst	r10,r0
	bf	@color
	nop
	bra	@dodec
	mov.w	r5,@r2
@color:
	mov.w	r4,@r2
@dodec:
	shll2	r0
	shll2	r0

	add	#2,r2
	dt	r7
	bf	@colloop

	add	r3,r2

	dt	r6
	bf	@rowloop

	rts
	nop
	cnop	0,4
	lits


; Set text position on the screen
; input
;	R4 = X pos
;	R5 = Y pos

	xdef	_TextXY
_TextXY
	mov.l	#_textx,r0
	mov.l	r4,@r0

	mov.l	#_texty,r0
	mov.l	r5,@r0

	rts
	nop

; Set text position on the screen
; input
;	R4 = foreground color
;	R5 = background color

	xdef	_TextColor
_TextColor
	mov.l	#_textfcolor,r0
	mov.l	r4,@r0

	mov.l	#_textbcolor,r0
	mov.l	r5,@r0

	rts
	nop

			
; print a string on he screen
; input
;	R4 = address of string to print

	xdef	_Gputs
_Gputs
	push	pr

	push	r8
	push	r9
	push	r10

	mov	r4,r6

	mov.l	#_textx,r0
	mov.l	@r0,r2

	mov.l	#_texty,r0
	mov.l	@r0,r3

	mov.l	#_textfcolor,r0
	mov.l	@r0,r4
	
	mov.l	#_textbcolor,r0
	mov.l	@r0,r5

@printloop

	mov.b	@r6+,r0
	cmp/eq	#0,r0
	bt	@fini

	push	r1,r2,r3,r6
	bsr	Gputc
	mov	r0,r1
	pop	r6,r3,r2,r1

	bra	@printloop

	add	#8,r2

@fini
	mov.l	#_textx,r0
	mov.l	r2,@r0

	pop	r10
	pop	r9
	pop	r8

	pop	pr
	rts
	nop

