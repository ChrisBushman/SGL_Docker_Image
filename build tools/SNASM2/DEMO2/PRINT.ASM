; convert a binary number to hex text
; input
;	R4 = address of buffer to put string
;	R5 = number to convert
;	R6 = number of digits in number
	xdef	_ItoH
_ItoH
	push	pr

	mov.l	#hextab,r1
	add	r6,r4
	add	#1,r4
	mov	#0,r0
	mov.b	r0,@-r4
	mov	#$0F,r2
@convertloop:
	mov	r5,r0
	and	r2,r0
	mov.b	@(r0,r1),r0
	mov.b	r0,@-r4
	shlr2	r5

	dt	r6
	bf/s	@convertloop
	shlr2	r5
	

	pop	pr
	rts
	nop

hextab
	dc.b	"0123456789ABCDEF"


